import assert from "node:assert/strict";
import { CITY_CASES } from "../../public/games/city/cases.mjs";
import { integratedStep, canEnterQuestion, canOpenWorksite } from "../../public/games/city/integrated-journey.mjs";
import { sanitizeLab } from "../../public/games/city/build-lab.mjs";
const first=CITY_CASES[0], second=CITY_CASES[1];
assert.equal(first.id, "repair-queue");
const empty=sanitizeLab(null);
assert.deepEqual(integratedStep({},empty), {kind:"question",caseId:first.id,index:0,missionId:null});
assert.equal(canOpenWorksite("workshop-link",{},empty),false);
assert.equal(canEnterQuestion(second.id,{},empty),false);
const decided={[first.id]:first.options[0].id};
assert.equal(integratedStep(decided,empty).kind,"build");
assert.equal(integratedStep(decided,empty).missionId,"workshop-link");
assert.equal(canOpenWorksite("workshop-link",decided,empty),true);
assert.equal(canOpenWorksite("clinic-power",decided,empty),false);
assert.equal(canEnterQuestion(second.id,decided,empty),false);
const solved=Array(25).fill(null);
solved[5]={kind:"bend",turn:1};
for(let i=6;i<=8;i++)solved[i]={kind:"straight",turn:1};
solved[9]={kind:"bend",turn:2};
const valid=sanitizeLab({boards:{"workshop-link":solved},tested:["workshop-link"]});
assert.equal(integratedStep(decided,valid).caseId,second.id);
assert.equal(integratedStep(decided,valid).kind,"question");
assert.equal(canEnterQuestion(second.id,decided,valid),true);
assert.equal(canOpenWorksite("workshop-link",decided,valid),true);
const revised=sanitizeLab({boards:{"workshop-link":solved.map((p,i)=>i===7?null:p)},tested:["workshop-link"]});
assert.equal(integratedStep(decided,revised).kind,"build");
assert.equal(canEnterQuestion(second.id,decided,revised),false);
const allDecided=Object.fromEntries(CITY_CASES.map(c=>[c.id,c.options[0].id]));
assert.equal(integratedStep(allDecided,empty).missionId,"workshop-link");
assert.equal(Object.keys(allDecided).length,36);
console.log("PASS: mandatory decision-before-build and build-before-next-question, no arbitrary menu skipping, safe revisits and revision re-lock.");
