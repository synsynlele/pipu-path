// Use one real dependency in the starting city's state, not a random paragraph.
export function chapterPressure(scenario, city) {
  if (scenario.chapter !== 2) return "";
  const linked = city.districts[scenario.dependsOn];
  if (!linked || !linked.built)
    return "A related service is not yet built. Your new district must plan around that gap.";
  if (linked.service < 42)
    return (
      linked.name +
      " is struggling in your city. This makes the new challenge harder until that service improves."
    );
  if (linked.service >= 65)
    return (
      linked.name +
      " is thriving in your city. You can build on that strength, but its upkeep still matters."
    );
  return (
    linked.name +
    " is active but has limits. Coordinate with that service while deciding what to build."
  );
}
